import fs from "fs";
import path from "path";
import solc from "solc";

const ROOT = path.resolve(process.cwd());
const CONTRACTS_DIR = path.join(ROOT, "contracts");
const ARTIFACTS_DIR = path.join(ROOT, "artifacts");
const ABI_OUT_DIR = path.join(ROOT, "src", "lib", "abi");

function findImports(importPath: string): { contents?: string; error?: string } {
  if (importPath.startsWith("@rome-protocol/rome-solidity/")) {
    const rel = importPath.replace("@rome-protocol/rome-solidity/", "");
    const localPath = path.join(CONTRACTS_DIR, "rome-solidity", rel);
    if (fs.existsSync(localPath)) {
      return { contents: fs.readFileSync(localPath, "utf8") };
    }
  }
  const fullPath = path.join(CONTRACTS_DIR, importPath);
  if (fs.existsSync(fullPath)) {
    return { contents: fs.readFileSync(fullPath, "utf8") };
  }
  return { error: `File not found: ${importPath}` };
}

export function compileContracts() {
  const yieldPortSource = fs.readFileSync(path.join(CONTRACTS_DIR, "RomeYieldPort.sol"), "utf8");
  const mocksSource = fs.readFileSync(path.join(CONTRACTS_DIR, "Mocks.sol"), "utf8");

  const input = {
    language: "Solidity",
    sources: {
      "RomeYieldPort.sol": { content: yieldPortSource },
      "Mocks.sol": { content: mocksSource },
    },
    settings: {
      optimizer: {
        enabled: true,
        runs: 1,
      },
      evmVersion: "paris",
      outputSelection: {
        "*": {
          "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
        },
      },
    },
  };

  const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));

  if (output.errors) {
    const fatal = output.errors.filter((e: { severity: string }) => e.severity === "error");
    for (const err of output.errors) {
      console.log(err.formattedMessage);
    }
    if (fatal.length > 0) {
      throw new Error(`Compilation failed with ${fatal.length} error(s)`);
    }
  }

  fs.mkdirSync(ARTIFACTS_DIR, { recursive: true });
  fs.mkdirSync(ABI_OUT_DIR, { recursive: true });

  const compiled: Record<string, { abi: unknown[]; bytecode: `0x${string}`; deployedBytecode: `0x${string}` }> = {};

  for (const [fileName, fileContracts] of Object.entries(output.contracts)) {
    for (const [contractName, data] of Object.entries(fileContracts as Record<string, any>)) {
      const artifact = {
        contractName,
        sourceName: fileName,
        abi: data.abi,
        bytecode: (`0x${data.evm.bytecode.object}`) as `0x${string}`,
        deployedBytecode: (`0x${data.evm.deployedBytecode.object}`) as `0x${string}`,
      };
      fs.writeFileSync(path.join(ARTIFACTS_DIR, `${contractName}.json`), JSON.stringify(artifact, null, 2));
      compiled[contractName] = artifact;
    }
  }

  // Write TypeScript ABI & Bytecode module for Next.js frontend
  const yp = compiled["RomeYieldPort"];
  const tsContent = `// Auto-generated by scripts/compile.ts — DO NOT EDIT MANUALLY
export const ROME_YIELD_PORT_ABI = ${JSON.stringify(yp.abi, null, 2)} as const;

export const ROME_YIELD_PORT_BYTECODE = "${yp.bytecode}" as const;
`;
  fs.writeFileSync(path.join(ABI_OUT_DIR, "RomeYieldPort.ts"), tsContent);
  console.log("✅ Compiled RomeYieldPort.sol & Mocks.sol successfully!");
  return compiled;
}

if (process.argv[1] && process.argv[1].endsWith("compile.ts")) {
  compileContracts();
}
